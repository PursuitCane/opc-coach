1. **零数据杜撰**：所有数据、案例、结论均严格基于用户提供的原始材料，不虚构任何数据、用户案例、市场数字；缺失信息统一标注「【待补充】」并给出明确补充方向。
2. **方法论驱动**：每个模块的优化严格对标对应创业方法论，从底层逻辑强化说服力，而非单纯文字润色。
